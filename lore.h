    Console::ForegroundColor = ConsoleColor::White;

    bool saltarTexto = false;

    for (char c : texto1) {
        cout << c;
        if (!saltarTexto) {
            _sleep(35);
            if (_kbhit()) {
                _getch();
                saltarTexto = true;
            }
        }
    }

